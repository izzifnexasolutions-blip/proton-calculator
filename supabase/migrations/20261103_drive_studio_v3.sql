-- Uses existing Supabase project qagsczjxzshjxmmxvkbq and existing sales_staff_profiles.
-- Bootstrap admin using a reviewed auth.users UUID, never email matching or user_metadata.

begin;

-- Supabase Auth users may read only their OWN staff profile (not write roles).
create policy "drive3d_staff_self_read" on public.sales_staff_profiles
  for select to authenticated using (user_id = (select auth.uid()));

create table if not exists public.drive_3d_listings (
  id uuid primary key default gen_random_uuid(),
  listing_key text not null unique check (listing_key ~ '^[A-Za-z0-9_-]{3,64}$'),
  owner_id uuid not null references auth.users(id),
  manifest jsonb not null default '{}'::jsonb,
  status text not null default 'draft' check (status in ('draft','review','approved','published','archived')),
  version integer not null default 1 check(version >= 1),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz
);
create index if not exists idx_drive3d_owner on public.drive_3d_listings(owner_id,status);
alter table public.drive_3d_listings enable row level security;
grant select,insert,update on public.drive_3d_listings to authenticated;
create policy "drive3d_owner_read" on public.drive_3d_listings for select to authenticated
 using(owner_id = (select auth.uid()) and exists(select 1 from public.sales_staff_profiles s where s.user_id=(select auth.uid()) and s.role='admin' and s.is_active));
create policy "drive3d_owner_insert" on public.drive_3d_listings for insert to authenticated
 with check(owner_id = (select auth.uid()) and status='draft' and exists(select 1 from public.sales_staff_profiles s where s.user_id=(select auth.uid()) and s.role='admin' and s.is_active));
create policy "drive3d_owner_update" on public.drive_3d_listings for update to authenticated
 using(owner_id = (select auth.uid()) and exists(select 1 from public.sales_staff_profiles s where s.user_id=(select auth.uid()) and s.role='admin' and s.is_active))
 with check(owner_id = (select auth.uid()) and exists(select 1 from public.sales_staff_profiles s where s.user_id=(select auth.uid()) and s.role='admin' and s.is_active));

-- PUBLIC API: ONLY sanitized approved manifests, never original upload paths.
create table if not exists public.drive_3d_public (
 listing_id uuid primary key references public.drive_3d_listings(id),
 listing_key text not null unique,
 published boolean not null default false,
 version integer not null default 1,
 manifest jsonb not null,
 published_at timestamptz not null default now()
);
alter table public.drive_3d_public enable row level security;
grant select on public.drive_3d_public to anon,authenticated;
create policy "drive3d_public_read_published" on public.drive_3d_public for select to anon,authenticated using(published = true);

create table if not exists public.drive_3d_public_history (
 id bigint generated by default as identity primary key,
 listing_id uuid not null references public.drive_3d_listings(id),
 version integer not null,
 public_manifest jsonb not null,
 action text not null check(action in ('publish','unpublish','rollback')),
 actor_id uuid not null references auth.users(id),
 created_at timestamptz not null default now()
);
alter table public.drive_3d_public_history enable row level security;
grant select on public.drive_3d_public_history to authenticated;
create policy "drive3d_history_admin_read" on public.drive_3d_public_history for select to authenticated
 using(exists(select 1 from public.sales_staff_profiles s where s.user_id=(select auth.uid()) and s.role='admin' and s.is_active));

-- New buckets; no changes to existing car-media or variant-media.
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('drive3d-private','drive3d-private',false,31457280,array['image/webp','model/gltf-binary']),
('drive3d-published','drive3d-published',true,31457280,array['image/webp','model/gltf-binary'])
on conflict (id) do nothing;
create policy "drive3d_private_admin_insert" on storage.objects for insert to authenticated
 with check(bucket_id='drive3d-private' and exists(select 1 from public.sales_staff_profiles s where s.user_id=(select auth.uid()) and s.role='admin' and s.is_active));
create policy "drive3d_private_admin_select" on storage.objects for select to authenticated
 using(bucket_id='drive3d-private' and exists(select 1 from public.sales_staff_profiles s where s.user_id=(select auth.uid()) and s.role='admin' and s.is_active));
create policy "drive3d_public_admin_insert" on storage.objects for insert to authenticated
 with check(bucket_id='drive3d-published' and exists(select 1 from public.sales_staff_profiles s where s.user_id=(select auth.uid()) and s.role='admin' and s.is_active));

-- Restrict public mutations to admin-validated functions, not browser-supplied status flags.
create or replace function public.drive3d_publish(p_listing_id uuid,p_public_manifest jsonb)
returns void language plpgsql security definer set search_path = '' as $$
declare v public.drive_3d_listings%rowtype; m jsonb; photo jsonb; p text; k text;
begin
 if (select auth.uid()) is null or not exists(select 1 from public.sales_staff_profiles s where s.user_id=(select auth.uid()) and s.role='admin' and s.is_active) then
  raise exception 'Admin role required';
 end if;
 select * into v from public.drive_3d_listings where id=p_listing_id and owner_id=(select auth.uid()) for update;
 if not found or v.status<>'approved' or coalesce((v.manifest->>'rights')::boolean,false) is not true or coalesce((v.manifest->>'privacy')::boolean,false) is not true then
  raise exception 'Draft must be approved, owned and rights/privacy reviewed';
 end if;
 k := v.listing_key;
 if p_public_manifest->>'listingKey' is distinct from k or jsonb_typeof(p_public_manifest->'photos')<>'array' then raise exception 'Invalid public manifest';end if;
 if (p_public_manifest ? 'privatePath') or (p_public_manifest ? 'originals') then raise exception 'Private data cannot be published';end if;
 if coalesce(p_public_manifest->>'assetPath','')<>'' and left(p_public_manifest->>'assetPath',length('models/'||k||'/'))<>'models/'||k||'/' then raise exception 'Invalid GLB path';end if;
 for photo in select value from jsonb_array_elements(p_public_manifest->'photos') loop
  p:=photo->>'path';if p is null or left(p,length('photos/'||k||'/'))<>'photos/'||k||'/' then raise exception 'Invalid public media path';end if;
 end loop;
 -- Explicit public fields whitelist; private source manifest NEVER copied to public table.
 m:=jsonb_build_object('schemaVersion','1.0.0','listingKey',k,'vehicle',p_public_manifest->'vehicle','sourceType',p_public_manifest->'sourceType','disclaimer','Maklumat belum disahkan sebagai spesifikasi OEM atau pemeriksaan fizikal.','inspection',jsonb_build_object('status','unverified'),'photos',p_public_manifest->'photos','assetPath',p_public_manifest->'assetPath','nodeMap',p_public_manifest->'nodeMap','hinges',p_public_manifest->'hinges','featureAvailability',p_public_manifest->'featureAvailability','sourceAttribution',p_public_manifest->'sourceAttribution');
 insert into public.drive_3d_public(listing_id,listing_key,published,version,manifest,published_at)
 values(v.id,k,true,v.version,m,now())
 on conflict(listing_id) do update set published=true,version=excluded.version,manifest=excluded.manifest,published_at=now();
 insert into public.drive_3d_public_history(listing_id,version,public_manifest,action,actor_id)values(v.id,v.version,m,'publish',(select auth.uid()));
 update public.drive_3d_listings set status='published',published_at=now(),updated_at=now(),version=version+1 where id=v.id;
end;$$;
revoke all on function public.drive3d_publish(uuid,jsonb) from public,anon;
grant execute on function public.drive3d_publish(uuid,jsonb) to authenticated;

create or replace function public.drive3d_unpublish(p_listing_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare v public.drive_3d_listings%rowtype;
begin
 if (select auth.uid()) is null or not exists(select 1 from public.sales_staff_profiles s where s.user_id=(select auth.uid()) and s.role='admin' and s.is_active) then raise exception 'Admin role required';end if;
 select * into v from public.drive_3d_listings where id=p_listing_id and owner_id=(select auth.uid()) and status='published' for update;
 if not found then raise exception 'No published listing owned by admin';end if;
 update public.drive_3d_public set published=false where listing_id=v.id;
 insert into public.drive_3d_public_history(listing_id,version,public_manifest,action,actor_id)
 select v.id,version,manifest,'unpublish',(select auth.uid()) from public.drive_3d_public where listing_id=v.id;
 update public.drive_3d_listings set status='approved',updated_at=now() where id=v.id;
end;$$;
revoke all on function public.drive3d_unpublish(uuid) from public,anon;
grant execute on function public.drive3d_unpublish(uuid) to authenticated;
commit;